/**
 * 목적격 조사를 붙입니다. 한글 음절의 종성 유무로 을/를이 갈리므로 유니코드로 계산합니다.
 * 한글로 끝나지 않으면 조사를 붙이지 않고 그대로 둡니다.
 */
export function withObjectParticle(word: string) {
  const last = word.trim().slice(-1);
  const code = last.charCodeAt(0);
  if (code < 0xac00 || code > 0xd7a3) return word;
  return `${word}${(code - 0xac00) % 28 === 0 ? "를" : "을"}`;
}

